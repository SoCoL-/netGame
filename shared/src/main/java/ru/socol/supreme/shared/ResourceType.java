package ru.socol.supreme.shared;

/**
 * Тип ресурса. Железо размещается на карте фиксированными месторождениями
 * (см. GameConstants.IRON_DEPOSITS) и требует здание добычи, чтобы его
 * реально добывать — самого здания в игре пока нет, месторождения пока
 * только обозначены на карте (GameScreen.drawIronDeposits). Электричество
 * на карте не размещается вообще — его будет производить только
 * электростанция, тоже пока не реализованная. Хранение и подсчёт (сколько
 * у игрока того и другого) уже готово — см. PlayerResources.
 */
public enum ResourceType {
    IRON,
    ELECTRICITY
}
