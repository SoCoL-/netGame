package ru.socol.supreme.shared;

/**
 * Все "магические числа" игры, общие для всех юнитов и не зависящие от их
 * типа, собраны здесь (лимиты, тикрейт, размеры карты и зданий) — и на
 * сервере, и на клиенте. Скорость, урон и дальность атаки — то, чем
 * реально отличаются типы юнитов друг от друга — вынесены в units.json
 * (см. UnitDefinitions), не сюда.
 */
public final class GameConstants {

    private GameConstants() {
    }

    /** Всего 2 игрока в игре. */
    public static final int MAX_PLAYERS = 2;

    /** Суммарный лимит юнитов на всю игру (не на игрока, а на обоих вместе). */
    public static final int MAX_TOTAL_UNITS = 300;

    public static final int TCP_PORT = 54555;

    /** Пока не используется: весь трафик сейчас идёт по TCP (см. GameClient.connect() / GameServer.start()). */
    public static final int UDP_PORT = 54777;

    /**
     * Размер буферов KryoNet под сериализацию сообщений. Server()/Client()
     * без аргументов используют крошечные буферы по умолчанию (16384 байт
     * на запись и всего 2048 — на один объект). Этого хватало, пока
     * WorldSnapshot был маленьким, но с ростом числа юнитов и особенно
     * после того как в UnitSnapshot добавился pathPoints (для отладочной
     * отрисовки маршрута — см. GameScreen) один снапшот на несколько
     * десятков юнитов уже не помещается в 2048 байт: сериализация падает с
     * переполнением буфера (баг: воспроизводился на ~40 юнитах). На
     * MAX_TOTAL_UNITS с юнитами, огибающими препятствия по всей сетке,
     * оценка худшего случая — десятки килобайт; 1 МБ даёт большой запас.
     */
    public static final int NETWORK_WRITE_BUFFER_SIZE = 1024 * 1024;
    public static final int NETWORK_OBJECT_BUFFER_SIZE = 1024 * 1024;

    /** На каком расстоянии до цели юнит считается прибывшим и останавливается. */
    public static final float ARRIVE_THRESHOLD = 2f;

    /**
     * Условный радиус юнита — используется для отрисовки на клиенте и как
     * реальный радиус столкновений в CollisionSystem (два юнита ближе
     * 2×UNIT_RADIUS друг к другу считаются перекрывающимися и
     * расталкиваются). Одинаков у всех типов — в отличие от здоровья,
     * скорости, скорострельности, урона и дальности атаки/агрессии,
     * которые теперь заданы по типу в units.json (см. UnitDefinitions):
     * этот, в отличие от них, не про боевые характеристики, а про то,
     * какого юнит физически размера, и её вынос в данные пока не давал
     * бы ничего, кроме лишнего слоя.
     */
    public static final float UNIT_RADIUS = 10f;

    /**
     * Запас, на который Pathfinding "раздувает" препятствия (воду, здания)
     * при планировании пути — сверх их реального размера. Без этого A*
     * мог выбрать клетку, чей центр формально снаружи препятствия, но
     * ближе UNIT_RADIUS к его краю — CollisionSystem тут же вытолкнула бы
     * юнита обратно, а он (после доворота курса в MovementSystem) тут же
     * пошёл бы туда снова, зависнув в вечном топтании у стены. Запас чуть
     * больше UNIT_RADIUS — на случай, если юнит "прибыл" не точно в центр
     * клетки, а где-то в пределах ARRIVE_THRESHOLD от него.
     */
    public static final float PATH_CLEARANCE = UNIT_RADIUS + ARRIVE_THRESHOLD;

    /** Размер карты по каждой оси. Юниты, здания и камера не выходят за эти границы. */
    public static final float MAP_WIDTH = 2000f;
    public static final float MAP_HEIGHT = 2000f;

    /**
     * Препятствие посередине карты — вода. Блокирует ХОЖДЕНИЕ (юниты
     * обходят её по Pathfinding), но не дальность атаки — стрелять через
     * воду можно, это сознательное упрощение (нет отдельной проверки
     * "линии обзора" для боя, только для движения).
     */
    public static final float WATER_MIN_X = 700f;
    public static final float WATER_MAX_X = 1300f;
    public static final float WATER_MIN_Y = 700f;
    public static final float WATER_MAX_Y = 1300f;

    /**
     * Месторождения железа — по 2 на игрока, симметрично, в открытом
     * пространстве недалеко от его же дома/казармы (зазор от построек ~100
     * юнитов, проверено численно). Каждая запись — {x, y}. В отличие от
     * воды/зданий, НЕ препятствие для движения — юниты спокойно проходят
     * прямо через них, это просто точка на карте, а не физический объект.
     * Здание добычи (см. IRON_MINE_* ниже) можно поставить только СЮДА,
     * "прилипая" к одной из этих точек — см. GameScreen (превью при
     * постройке) и GameServer.handlePlaceIronMine (серверная проверка).
     */
    public static final float[][] IRON_DEPOSITS = {
            {500f, 200f}, {200f, 500f},     // игрок 0
            {1500f, 1800f}, {1800f, 1500f}, // игрок 1
    };

    /**
     * Базовая вместимость хранилища ресурса — доступна игроку всегда,
     * даже без единого здания IRON_STORAGE/ELECTRICITY_STORAGE (иначе
     * добывающее здание было бы бесполезно до постройки первого
     * хранилища — слишком жёстко для старта). Здания-хранилища
     * добавляют к ней BuildingDefinitions.storageCapacityFor(type) за
     * каждое — см. ResourceExtractionSystem, она же считает итоговую
     * вместимость заново каждый тик. Раздельные константы, а не одна
     * общая: у ресурсов сильно разный масштаб потока (электростанция —
     * 150/сек, шахта железа — 20/сек), одно и то же число было бы или
     * тесным для электричества, или бессмысленно огромным для железа.
     */
    public static final float IRON_BASE_CAPACITY = 300f; // ровно стоимость одного стрелка по железу
    public static final float ELECTRICITY_BASE_CAPACITY = 2000f; // ~13 сек добычи на полной ставке электростанции

    /**
     * Допуск на погрешность округления float при проверке "хватает ли
     * ресурсов на этот тик" в ProductionSystem/BuildSystem — НЕ реальная
     * нехватка ресурса, а типичный дребезг плавающей точки на последнем
     * тике постройки: после сотен маленьких вычитаний remaining/resources
     * и tick-стоимость, которые математически должны совпасть ровно,
     * расходятся в 14-15 знаке (например, доступно 0.017644369971943520,
     * а по формуле нужно 0.017644369971944070 — на 16 порядков меньше,
     * чем сама стоимость постройки). Без допуска строгое сравнение
     * "хватает ли" иногда решает, что не хватает, ресурс не списывается,
     * remaining не уменьшается — и постройка зависает на этом самом тике
     * навсегда, так и не завершившись. 0.001 — на три порядка больше
     * типичного дребезга, но всё равно на много порядков меньше самой
     * скромной реальной стоимости (десятки единиц), так что реальную
     * нехватку ресурса этот допуск замаскировать не может.
     */
    public static final float RESOURCE_EPSILON = 0.001f;

    /** Базовая вместимость по типу ресурса — используется ResourceExtractionSystem вместо отдельных if/else на каждый тип. */
    public static float baseCapacityFor(ResourceType type) {
        return type == ResourceType.ELECTRICITY ? ELECTRICITY_BASE_CAPACITY : IRON_BASE_CAPACITY;
    }

    /** Размер клетки сетки для поиска пути (Pathfinding) — 2000/50 = 40x40 клеток. */
    public static final float PATH_GRID_CELL_SIZE = 50f;

    // Туман войны — своя сетка, отдельная от Pathfinding: клетка 50 (та
    // же, что у поиска пути) достаточна для обхода препятствий, но у
    // самой маленькой дальности обзора в игре (70, у зданий) давала
    // всего 2.8 клетки в поперечнике — по сути крестик, а не круг, из-за
    // чего открытие тумана выглядело квадратным, а не круглым, хотя сама
    // проверка видимости (markVisibleCircle) всегда была честной по
    // расстоянию. Клетка 25 даёт той же дальности уже 5.6 в поперечнике
    // — заметно круглее на глаз, а самой большой (250, у стрелка) — 20,
    // почти гладкая окружность. FOG_GRID_WIDTH/HEIGHT — целое число
    // клеток на всю карту, MAP_WIDTH/HEIGHT кратны 25, деление ровное.
    public static final float FOG_GRID_CELL_SIZE = 25f;
    public static final int FOG_GRID_WIDTH = (int) (MAP_WIDTH / FOG_GRID_CELL_SIZE);
    public static final int FOG_GRID_HEIGHT = (int) (MAP_HEIGHT / FOG_GRID_CELL_SIZE);
    // Через сколько секунд после потери видимости клетка снова закрывается
    // туманом — см. GameServer.updateFogOfWar.
    public static final float FOG_REVEAL_GRACE_PERIOD = 2f;

    /**
     * Раньше было единое время постройки юнита на всех — теперь у каждого
     * типа своё (UnitDefinitions.buildTimeFor, появилось вместе со
     * штурмовиком и его 12 секундами вместо стандартных 10). Оставлена
     * только как запасное значение на клиенте (GameScreen
     * .drawBuildingInfoPanel) для доли прогресс-бара — если по какой-то
     * причине тип строящегося юнита ещё не известен (снапшот пуст),
     * не должна использоваться сервером напрямую нигде.
     */
    public static final float UNIT_BUILD_TIME = 10f;

    /** Частота обновления симуляции на сервере. */
    public static final float SERVER_TICK_RATE = 1f / 30f;

    /** Частота рассылки снапшотов мира клиентам. Также используется клиентом как длительность интерполяции. */
    public static final float SNAPSHOT_RATE = 1f / 15f;
}
