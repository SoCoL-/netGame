package ru.socol.supreme.shared.network.messages;

/**
 * Клиент -> сервер: "построй здание добычи железа на месторождении с этим
 * индексом" (индекс в GameConstants.IRON_DEPOSITS). Шлётся только когда
 * клиент сам считает точку подходящей (курсор был "прилипшим" к
 * месторождению в момент клика, см. GameScreen) — но финальное решение
 * всегда за сервером (GameServer.handlePlaceIronMine): индекс в границах
 * и месторождение ещё не занято другим зданием добычи.
 *
 * builderUnitIds — те строители, что были выделены в момент подтверждения
 * размещения (см. GameScreen.touchDown): раз меню постройки теперь
 * открывается только когда выделен строитель или группа строителей, тех
 * же самых строителей логично сразу отправить строить только что
 * поставленное здание, а не заставлять игрока ещё раз выделять их и
 * кликать правой кнопкой. Клиент в момент отправки ЭТОГО запроса ещё не
 * знает unitId будущего здания (его назначит только сервер при
 * создании) — поэтому список строителей едет вместе с заявкой на
 * размещение, а не отдельным BuildOrderRequest следом: назначение
 * происходит на сервере сразу после spawnBuilding, когда id уже известен.
 */
public class PlaceIronMineRequest {

    public int depositIndex;
    public int[] builderUnitIds;

    public PlaceIronMineRequest() {
    }
}
